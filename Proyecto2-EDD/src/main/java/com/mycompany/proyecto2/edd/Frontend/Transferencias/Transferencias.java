    private void inicializarTabla() {
        String[] columnas = {
            "No.", "TITULO", "AUTOR", "ISBN", "ACCION"};

        modeloTablaLibros = new DefaultTableModel(columnas, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return column == 4;
            }
        };

        tablaLibros = new JTable(modeloTablaLibros);

        tablaLibros.setSelectionMode(javax.swing.ListSelectionModel.SINGLE_SELECTION);
        tablaLibros.getTableHeader().setReorderingAllowed(false);
        tablaLibros.getColumnModel().getColumn(0).setPreferredWidth(25);
        tablaLibros.getColumnModel().getColumn(0).setPreferredWidth(50);
        tablaLibros.getColumnModel().getColumn(1).setPreferredWidth(50);
        tablaLibros.getColumnModel().getColumn(2).setPreferredWidth(50);
        tablaLibros.getColumnModel().getColumn(3).setPreferredWidth(50);

        tablaLibros.getColumn("ACCION").setCellRenderer(new ButtonRenderTr());
        tablaLibros.getColumn("ACCION").setCellEditor(new ButtonEditorTr(new JCheckBox(), modeloTablaLibros, this.sistema, cbOrigen, cbDestino, chk1, panelColas));
        JScrollPane scrollPane = new JScrollPane(tablaLibros);
        scrollPane.setPreferredSize(new java.awt.Dimension(4, 341));

        panel2.removeAll();
        panel2.setLayout(new java.awt.BorderLayout());
        panel2.add(scrollPane, java.awt.BorderLayout.CENTER);
        panel2.revalidate();
        panel2.repaint();
    }

    private void buscarBibliotecas() {
        this.bibliotecas = this.sistema.getBibliotecas();
        cbOrigen.removeAllItems();
        cbDestino.removeAllItems();
        if (bibliotecas.isEmpty()) {
            cbOrigen.addItem("NO HAY BIBLIOTECAS");
            cbDestino.addItem("NO HAY BIBLIOTECAS");
        } else {
            for (Biblioteca e : this.bibliotecas) {
                cbDestino.addItem(e.getNombre());
                cbOrigen.addItem(e.getNombre());
            }
        }
    }

    private void ordenarLibros() {
        String nombreBiblioteca = (String) cbOrigen.getSelectedItem();

        List<Object[]> datos = sistema.ordenarLibrosDeBibliotecaRed(nombreBiblioteca, "TITULO", "BURBUJA");

        modeloTablaLibros.setRowCount(0);
        for (Object[] fila : datos) {
            modeloTablaLibros.addRow(fila);
        }

        tablaLibros.revalidate();
        tablaLibros.repaint();
    }

    private void inicializarPanelColas() {
        panelColas = new PanelColas(this.sistema);
        JScrollPane scrollColas = new JScrollPane(panelColas);
        scrollColas.setPreferredSize(new Dimension(900, 250));
        scrollColas.setVerticalScrollBarPolicy(JScrollPane.VERTICAL_SCROLLBAR_ALWAYS);

        panelInferior.removeAll();
        panelInferior.setLayout(new BorderLayout());
        panelInferior.add(scrollColas, BorderLayout.CENTER);
        panelInferior.revalidate();
        panelInferior.repaint();
    }

