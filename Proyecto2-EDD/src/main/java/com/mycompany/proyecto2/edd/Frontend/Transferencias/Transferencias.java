    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
        ordenarLibros();
        String origen = cbOrigen.getSelectedItem().toString();
        String destino = cbDestino.getSelectedItem().toString();
        boolean porTiempo = chk1.isSelected();
        generador = new GeneradorGraphviz();
        String path = generador.generarImagenRutaOptima(this.sistema.getGrafoRed(), origen, destino, porTiempo);

        if (path != null) {
            ImageIcon icon = new ImageIcon(path);
            Image image = icon.getImage().getScaledInstance(lblImagen.getWidth(), lblImagen.getHeight(), Image.SCALE_SMOOTH);
            lblImagen.setIcon(new ImageIcon(image));
        } else {
            JOptionPane.showMessageDialog(this, generador.getMensaje(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnCalcularActionPerformed

