    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        int indexOrigen = cbOrigen.getSelectedIndex();
        int indexDestino = cbDestino.getSelectedIndex();
        Biblioteca origen = bibliotecas.get(indexOrigen);
        Biblioteca destino = bibliotecas.get(indexDestino);
        int tiempo = (Integer) sp1.getValue();
        int precio = (Integer) sp2.getValue();
        if (indexDestino != indexOrigen) {
            if (tiempo <= 0 && precio <= 0) {
                JOptionPane.showMessageDialog(this,
                        "DEBES DE INGRESAR UN TIEMPO O PRECIO VALIDO",
                        "MENSAJE",
                        JOptionPane.ERROR_MESSAGE);
                return;
            }
            if (this.sistema.agregarConexion(origen.getNombre(), destino.getNombre(), tiempo, precio, this.chk1.isSelected())) {
                JOptionPane.showMessageDialog(this,
                        "CONEXION REALIZADA",
                        "MENSAJE",
                        JOptionPane.INFORMATION_MESSAGE);
                cargarDatos();
            } else {
                JOptionPane.showMessageDialog(this,
                        "NO SE PUDO REALIZAR LA CONEXION",
                        "MENSAJE",
                        JOptionPane.ERROR_MESSAGE);
            }

        } else {
            JOptionPane.showMessageDialog(this,
                    "DEBES DE SELECCIONAR DIFERENTES BIBLIOTECAS",
                    "MENSAJE",
                    JOptionPane.ERROR_MESSAGE);
        }


    }//GEN-LAST:event_btnAgregarActionPerformed

