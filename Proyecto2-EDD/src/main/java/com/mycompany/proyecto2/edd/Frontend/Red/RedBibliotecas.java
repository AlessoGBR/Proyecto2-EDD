    private void inicializarTabla() {
        String[] columnas = {
            "ORIGEN", "DESTINO", "TIEMPO (MS)", "COSTO", "ACCION"};

        modeloTablaRedes = new DefaultTableModel(columnas, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return column == 4;
            }
        };

        tablaRedes = new JTable(modeloTablaRedes);

        tablaRedes.setSelectionMode(javax.swing.ListSelectionModel.SINGLE_SELECTION);
        tablaRedes.getTableHeader().setReorderingAllowed(false);

        tablaRedes.getColumnModel().getColumn(0).setPreferredWidth(50);
        tablaRedes.getColumnModel().getColumn(1).setPreferredWidth(50);
        tablaRedes.getColumnModel().getColumn(2).setPreferredWidth(25);
        tablaRedes.getColumnModel().getColumn(3).setPreferredWidth(25);
        tablaRedes.getColumnModel().getColumn(4).setPreferredWidth(75);
        
         tablaRedes.getColumn("ACCION").setCellRenderer(new ButtonRenderRed());
        tablaRedes.getColumn("ACCION").setCellEditor(new ButtonEditorRed(new JCheckBox(), modeloTablaRedes, this.sistema));

        JScrollPane scrollPane = new JScrollPane(tablaRedes);
        scrollPane.setPreferredSize(new java.awt.Dimension(4, 341));

        panel2.removeAll();
        panel2.setLayout(new java.awt.BorderLayout());
        panel2.add(scrollPane, java.awt.BorderLayout.CENTER);
        panel2.revalidate();
        panel2.repaint();
    }

    private void buscarBibliotecas() {
        this.bibliotecas = this.sistema.getBibliotecas();
        cbOrigen.removeAllItems();
        cbDestino.removeAllItems();
        if (bibliotecas.isEmpty()) {
            cbOrigen.addItem("NO HAY BIBLIOTECAS");
            cbDestino.addItem("NO HAY BIBLIOTECAS");
        } else {
            for (Biblioteca e : this.bibliotecas) {
                cbDestino.addItem(e.getNombre());
                cbOrigen.addItem(e.getNombre());
            }
        }
    }

    private void cargarDatos() {
        modeloTablaRedes.setRowCount(0);

        List<Object[]> datos = this.sistema.obtenerConexionesParaTabla();

        for (Object[] fila : datos) {
            modeloTablaRedes.addRow(fila);
        }

        panel2.revalidate();
        panel2.repaint();
    }

    private void cargarImagen() {
        lblImagen = new JLabel();
        lblImagen.setHorizontalAlignment(SwingConstants.CENTER);
        lblImagen.setVerticalAlignment(SwingConstants.CENTER);
        lblImagen.setBackground(Color.WHITE);
        lblImagen.setOpaque(true);

        scrollImagen = new JScrollPane(lblImagen);
        scrollImagen.setVerticalScrollBarPolicy(JScrollPane.VERTICAL_SCROLLBAR_AS_NEEDED);
        scrollImagen.setHorizontalScrollBarPolicy(JScrollPane.HORIZONTAL_SCROLLBAR_AS_NEEDED);
        scrollImagen.getVerticalScrollBar().setUnitIncrement(16);

        panel3.removeAll();
        panel3.setLayout(new BorderLayout());
        panel3.add(scrollImagen, BorderLayout.CENTER);
        panel3.revalidate();
        panel3.repaint();
    }

    private void imagen() {
        String path = generador.generarImagenGrafo(this.sistema.getGrafoRed(), "GRAFO");

        if (path != null) {
            File archivo = new File(path);
            if (archivo.exists()) {
                try {
                    Image img = ImageIO.read(archivo);

                    int ancho = lblImagen.getWidth();
                    int alto = lblImagen.getHeight();
                    Image imgEscalada = img.getScaledInstance(ancho, alto, Image.SCALE_SMOOTH);

                    lblImagen.setIcon(new ImageIcon(imgEscalada));
                    lblImagen.setText(null);
                    lblImagen.revalidate();
                    lblImagen.repaint();
                } catch (IOException ex) {
                    JOptionPane.showMessageDialog(this,
                            "EROR AL CARGAR LA IMAGEN",
                            "Error", JOptionPane.ERROR_MESSAGE);
                }
            } else {
                JOptionPane.showMessageDialog(this,
                        "NO SE ENCONTRO LA IMAGEN GENERADA: " + path,
                        "Archivo no encontrado", JOptionPane.WARNING_MESSAGE);
            }
        } else {
            JOptionPane.showMessageDialog(this,
                    "NO SE PUDO GENERAR LA IMAGEN PARA EL GRAFO.",
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }
